-- ============================================================
-- V5 — Audit: operation_logs (Log_Operacion, US-16)
-- ============================================================
-- SQL portable: corre igual en H2 (dev/test) y PostgreSQL (Supabase).
-- Append-only desde la API: no se expone PUT/PATCH/DELETE, el controller
-- expuesto a SYSTEM_ADMIN es solo GET con filtros. El aspect de AOP es el
-- único que escribe aquí.
-- ============================================================

CREATE TABLE operation_logs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT,                              -- null para intentos de login con email inexistente
    action      VARCHAR(20)                 NOT NULL,
    entity      VARCHAR(60)                 NOT NULL,
    entity_id   BIGINT,
    detail      VARCHAR(500),
    ip_address  VARCHAR(45),
    occurred_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_operation_logs_action CHECK (action IN (
        'SIGN_IN', 'SIGN_IN_FAILED', 'CREATE', 'UPDATE', 'DELETE', 'PATCH',
        'APPROVE', 'REJECT', 'REGISTER', 'ASSIGN', 'UNASSIGN', 'UPLOAD'))
);

CREATE INDEX idx_operation_logs_user_id ON operation_logs (user_id);
CREATE INDEX idx_operation_logs_entity ON operation_logs (entity);
CREATE INDEX idx_operation_logs_occurred_at ON operation_logs (occurred_at);
