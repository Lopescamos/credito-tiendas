-- ============================================================
-- V4 — Billing: installments (Cuota_Cronograma), late_fees (Cargo_Mora),
--      payments (Pago_Realizado) + payment_allocations (Imputacion_Pago),
--      account_statements (Estado_Cuenta_Mensual) + account_statement_details
-- ============================================================
-- SQL portable: corre igual en H2 (dev/test) y PostgreSQL (Supabase).
-- credit_profile_id en installments está denormalizado para evitar joins entre BCs.
-- ============================================================

CREATE TABLE installments (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    credit_sale_id     BIGINT                      NOT NULL,
    credit_profile_id  BIGINT                      NOT NULL,
    number             INTEGER                     NOT NULL,
    due_date           DATE                        NOT NULL,
    capital            NUMERIC(12, 2)              NOT NULL,
    interest           NUMERIC(12, 2)              NOT NULL,
    fixed_installment  NUMERIC(12, 2)              NOT NULL,
    remaining_balance  NUMERIC(12, 2)              NOT NULL,
    status             VARCHAR(20)                 NOT NULL,
    payment_date       DATE,
    created_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_installments_sale_number UNIQUE (credit_sale_id, number),
    CONSTRAINT fk_installments_sale FOREIGN KEY (credit_sale_id) REFERENCES credit_sales (id),
    CONSTRAINT fk_installments_profile FOREIGN KEY (credit_profile_id) REFERENCES credit_profiles (id),
    CONSTRAINT ck_installments_status CHECK (status IN ('PENDING', 'OVERDUE', 'PAID_ON_TIME', 'PAID_LATE'))
);

CREATE INDEX idx_installments_profile_id ON installments (credit_profile_id);
CREATE INDEX idx_installments_sale_id ON installments (credit_sale_id);
CREATE INDEX idx_installments_due_date ON installments (due_date);

CREATE TABLE late_fees (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    installment_id BIGINT                      NOT NULL,
    days_late      INTEGER                     NOT NULL,
    amount         NUMERIC(12, 2)              NOT NULL,
    calculated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_late_fees_installment FOREIGN KEY (installment_id) REFERENCES installments (id),
    CONSTRAINT ck_late_fees_amounts CHECK (days_late >= 0 AND amount >= 0)
);

CREATE INDEX idx_late_fees_installment_id ON late_fees (installment_id);

CREATE TABLE payments (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    credit_profile_id BIGINT                      NOT NULL,
    total_amount      NUMERIC(12, 2)              NOT NULL,
    payment_date      DATE                        NOT NULL,
    payment_method    VARCHAR(20)                 NOT NULL,
    reference         VARCHAR(100),
    registered_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    created_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_payments_profile FOREIGN KEY (credit_profile_id) REFERENCES credit_profiles (id),
    CONSTRAINT ck_payments_method CHECK (
        payment_method IN ('CASH', 'BANK_TRANSFER', 'YAPE', 'PLIN', 'DEBIT_CARD', 'CREDIT_CARD')),
    CONSTRAINT ck_payments_amount CHECK (total_amount > 0)
);

CREATE INDEX idx_payments_profile_id ON payments (credit_profile_id);
CREATE INDEX idx_payments_payment_date ON payments (payment_date);

CREATE TABLE payment_allocations (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id      BIGINT                      NOT NULL,
    installment_id  BIGINT                      NOT NULL,
    late_fee_amount NUMERIC(12, 2)              NOT NULL,
    interest_amount NUMERIC(12, 2)              NOT NULL,
    capital_amount  NUMERIC(12, 2)              NOT NULL,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_payment_allocations_payment_installment UNIQUE (payment_id, installment_id),
    CONSTRAINT fk_payment_allocations_payment FOREIGN KEY (payment_id) REFERENCES payments (id),
    CONSTRAINT fk_payment_allocations_installment FOREIGN KEY (installment_id) REFERENCES installments (id),
    CONSTRAINT ck_payment_allocations_amounts CHECK (
        late_fee_amount >= 0 AND interest_amount >= 0 AND capital_amount >= 0)
);

CREATE INDEX idx_payment_allocations_installment_id ON payment_allocations (installment_id);

CREATE TABLE account_statements (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    credit_profile_id BIGINT                      NOT NULL,
    period            VARCHAR(7)                  NOT NULL,
    cutoff_date       DATE                        NOT NULL,
    previous_balance  NUMERIC(12, 2)              NOT NULL,
    period_purchases  NUMERIC(12, 2)              NOT NULL,
    period_payments   NUMERIC(12, 2)              NOT NULL,
    period_interest   NUMERIC(12, 2)              NOT NULL,
    period_late_fees  NUMERIC(12, 2)              NOT NULL,
    final_balance     NUMERIC(12, 2)              NOT NULL,
    created_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_account_statements_profile_period UNIQUE (credit_profile_id, period),
    CONSTRAINT fk_account_statements_profile FOREIGN KEY (credit_profile_id) REFERENCES credit_profiles (id),
    CONSTRAINT ck_account_statements_period_format CHECK (period LIKE '____-__')
);

CREATE INDEX idx_account_statements_profile_id ON account_statements (credit_profile_id);

CREATE TABLE account_statement_details (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_statement_id BIGINT                      NOT NULL,
    movement_type        VARCHAR(30)                 NOT NULL,
    description          VARCHAR(200)                NOT NULL,
    amount               NUMERIC(12, 2)              NOT NULL,
    date                 DATE                        NOT NULL,
    created_at           TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at           TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_account_statement_details_statement FOREIGN KEY (account_statement_id) REFERENCES account_statements (id),
    CONSTRAINT ck_account_statement_details_movement CHECK (
        movement_type IN ('PURCHASE', 'PAYMENT', 'INTEREST', 'LATE_FEE'))
);

CREATE INDEX idx_account_statement_details_statement_id ON account_statement_details (account_statement_id);
