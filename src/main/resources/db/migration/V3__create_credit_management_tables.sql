-- ============================================================
-- V3 — Credit Management: credit_profiles (Perfil_Credito_Cliente),
--      credit_sales (Venta_Credito) + sale_details (Detalle_Venta),
--      credit_purchase_requests (Solicitud_Compra_Credito)
--      + purchase_request_details (Detalle_Solicitud)
-- ============================================================
-- SQL portable: corre igual en H2 (dev/test) y PostgreSQL (Supabase).
-- Tasas en porcentaje anual NUMERIC(10,7); montos NUMERIC(12,2).
-- ============================================================

CREATE TABLE credit_profiles (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                 BIGINT                      NOT NULL,
    store_id                BIGINT                      NOT NULL,
    interest_rate           NUMERIC(10, 7)              NOT NULL,
    rate_type               VARCHAR(20)                 NOT NULL,
    capitalization_period   VARCHAR(20),
    late_interest_rate      NUMERIC(10, 7)              NOT NULL,
    late_interest_rate_type VARCHAR(20)                 NOT NULL,
    currency_id             BIGINT                      NOT NULL,
    credit_limit            NUMERIC(12, 2)              NOT NULL,
    max_term_days           INTEGER                     NOT NULL,
    cutoff_day              INTEGER                     NOT NULL,
    payment_day             INTEGER                     NOT NULL,
    active                  BOOLEAN                     NOT NULL,
    created_at              TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at              TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_credit_profiles_user_store UNIQUE (user_id, store_id),
    CONSTRAINT fk_credit_profiles_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_credit_profiles_store FOREIGN KEY (store_id) REFERENCES stores (id),
    CONSTRAINT fk_credit_profiles_currency FOREIGN KEY (currency_id) REFERENCES currencies (id),
    CONSTRAINT ck_credit_profiles_rate_type CHECK (rate_type IN ('EFFECTIVE', 'NOMINAL')),
    CONSTRAINT ck_credit_profiles_late_rate_type CHECK (late_interest_rate_type IN ('EFFECTIVE', 'NOMINAL')),
    CONSTRAINT ck_credit_profiles_capitalization CHECK (
        (rate_type = 'EFFECTIVE' AND capitalization_period IS NULL) OR
        (rate_type = 'NOMINAL' AND capitalization_period IN
            ('DAILY', 'BIWEEKLY', 'MONTHLY', 'BIMONTHLY', 'QUARTERLY', 'FOUR_MONTHLY', 'SEMIANNUAL', 'ANNUAL'))),
    CONSTRAINT ck_credit_profiles_rates CHECK (interest_rate >= 0 AND late_interest_rate >= 0),
    CONSTRAINT ck_credit_profiles_limit CHECK (credit_limit > 0),
    CONSTRAINT ck_credit_profiles_days CHECK (
        max_term_days > 0 AND cutoff_day BETWEEN 1 AND 28 AND payment_day BETWEEN 1 AND 28)
);

CREATE INDEX idx_credit_profiles_store_id ON credit_profiles (store_id);

-- origin_purchase_request_id / generated_sale_id se enlazan entre sí: sus FKs se agregan al final
CREATE TABLE credit_sales (
    id                              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    credit_profile_id               BIGINT                      NOT NULL,
    sale_date                       DATE                        NOT NULL,
    total_amount                    NUMERIC(12, 2)              NOT NULL,
    modality                        VARCHAR(20)                 NOT NULL,
    term_days                       INTEGER                     NOT NULL,
    grace_days                      INTEGER                     NOT NULL,
    installment_count               INTEGER                     NOT NULL,
    fixed_installment               NUMERIC(12, 2)              NOT NULL,
    financed_capital                NUMERIC(12, 2)              NOT NULL,
    interest_rate_snapshot          NUMERIC(10, 7)              NOT NULL,
    rate_type_snapshot              VARCHAR(20)                 NOT NULL,
    capitalization_period_snapshot  VARCHAR(20),
    late_interest_rate_snapshot     NUMERIC(10, 7)              NOT NULL,
    late_interest_rate_type_snapshot VARCHAR(20)                NOT NULL,
    status                          VARCHAR(20)                 NOT NULL,
    origin_purchase_request_id      BIGINT,
    created_at                      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at                      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_credit_sales_profile FOREIGN KEY (credit_profile_id) REFERENCES credit_profiles (id),
    CONSTRAINT ck_credit_sales_modality CHECK (modality IN ('SINGLE_PAYMENT', 'INSTALLMENTS')),
    CONSTRAINT ck_credit_sales_status CHECK (status IN ('ACTIVE', 'OVERDUE', 'PAID_ON_TIME', 'PAID_LATE')),
    CONSTRAINT ck_credit_sales_installments CHECK (
        (modality = 'SINGLE_PAYMENT' AND installment_count = 1) OR
        (modality = 'INSTALLMENTS' AND installment_count >= 2)),
    CONSTRAINT ck_credit_sales_amounts CHECK (total_amount > 0 AND financed_capital >= total_amount AND grace_days >= 0)
);

CREATE INDEX idx_credit_sales_profile_id ON credit_sales (credit_profile_id);

CREATE TABLE sale_details (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    credit_sale_id BIGINT                      NOT NULL,
    product_id     BIGINT                      NOT NULL,
    quantity       NUMERIC(10, 2)              NOT NULL,
    unit_price     NUMERIC(12, 2)              NOT NULL,
    subtotal       NUMERIC(12, 2)              NOT NULL,
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_sale_details_sale FOREIGN KEY (credit_sale_id) REFERENCES credit_sales (id),
    CONSTRAINT fk_sale_details_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT ck_sale_details_amounts CHECK (quantity > 0 AND unit_price > 0)
);

CREATE INDEX idx_sale_details_sale_id ON sale_details (credit_sale_id);

CREATE TABLE credit_purchase_requests (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    credit_profile_id BIGINT                      NOT NULL,
    requested_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    status            VARCHAR(20)                 NOT NULL,
    rejection_reason  VARCHAR(300),
    responded_at      TIMESTAMP(6) WITH TIME ZONE,
    generated_sale_id BIGINT,
    total_amount      NUMERIC(12, 2)              NOT NULL,
    created_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_credit_purchase_requests_profile FOREIGN KEY (credit_profile_id) REFERENCES credit_profiles (id),
    CONSTRAINT ck_credit_purchase_requests_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT ck_credit_purchase_requests_answer CHECK (
        (status = 'PENDING' AND responded_at IS NULL) OR
        (status = 'APPROVED' AND generated_sale_id IS NOT NULL AND responded_at IS NOT NULL) OR
        (status = 'REJECTED' AND rejection_reason IS NOT NULL AND responded_at IS NOT NULL))
);

CREATE INDEX idx_credit_purchase_requests_profile_id ON credit_purchase_requests (credit_profile_id);

CREATE TABLE purchase_request_details (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_request_id BIGINT                      NOT NULL,
    product_id          BIGINT                      NOT NULL,
    quantity            NUMERIC(10, 2)              NOT NULL,
    unit_price          NUMERIC(12, 2)              NOT NULL,
    subtotal            NUMERIC(12, 2)              NOT NULL,
    created_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_purchase_request_details_request FOREIGN KEY (purchase_request_id) REFERENCES credit_purchase_requests (id),
    CONSTRAINT fk_purchase_request_details_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT ck_purchase_request_details_amounts CHECK (quantity > 0 AND unit_price > 0)
);

CREATE INDEX idx_purchase_request_details_request_id ON purchase_request_details (purchase_request_id);

-- Enlace solicitud <-> venta generada (trazabilidad US-09)
ALTER TABLE credit_sales
    ADD CONSTRAINT fk_credit_sales_origin_request
        FOREIGN KEY (origin_purchase_request_id) REFERENCES credit_purchase_requests (id);

ALTER TABLE credit_purchase_requests
    ADD CONSTRAINT fk_credit_purchase_requests_generated_sale
        FOREIGN KEY (generated_sale_id) REFERENCES credit_sales (id);
