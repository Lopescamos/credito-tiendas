-- ============================================================
-- V1 — IAM: roles (Rol), users (Usuario), user_stores (Usuario_Tienda)
-- ============================================================
-- SQL portable: corre igual en H2 (dev/test) y PostgreSQL (Supabase).
-- Una migración aplicada NUNCA se edita: cualquier cambio va en una V nueva.
-- Los roles y el Admin Sistema inicial los siembra la app al arrancar
-- (iamApplicationReadyEventHandler), no esta migración.
-- ============================================================

CREATE TABLE roles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(30)                 NOT NULL,
    description VARCHAR(100),
    active      BOOLEAN                     NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_roles_name UNIQUE (name),
    CONSTRAINT ck_roles_name CHECK (name IN ('SYSTEM_ADMIN', 'STORE_ADMIN', 'CLIENT'))
);

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(100)                NOT NULL,
    first_name    VARCHAR(60)                 NOT NULL,
    last_name     VARCHAR(60)                 NOT NULL,
    password_hash VARCHAR(256)                NOT NULL,
    role_id       BIGINT                      NOT NULL,
    active        BOOLEAN                     NOT NULL,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT fk_users_role FOREIGN KEY (role_id) REFERENCES roles (id)
);

CREATE INDEX idx_users_role_id ON users (role_id);

-- store_id apunta a stores (Store Management). La FK se agrega en la migración que crea stores.
CREATE TABLE user_stores (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT                      NOT NULL,
    store_id    BIGINT                      NOT NULL,
    assigned_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    active      BOOLEAN                     NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_user_stores_user_store UNIQUE (user_id, store_id),
    CONSTRAINT fk_user_stores_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX idx_user_stores_store_id ON user_stores (store_id);
