-- ============================================================
-- V2 — Store Management: stores (Tienda), currencies (Moneda),
--      measurement_units (Unidad_Medida), products (Producto_Servicio)
-- ============================================================
-- SQL portable: corre igual en H2 (dev/test) y PostgreSQL (Supabase).
-- Montos como NUMERIC(12,2) (equivalente a DECIMAL(12,2) en ambos motores).
-- Monedas y unidades las siembra la app al arrancar
-- (storeManagementApplicationReadyEventHandler), no esta migración.
-- ============================================================

CREATE TABLE stores (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ruc        VARCHAR(11)                 NOT NULL,
    legal_name VARCHAR(120)                NOT NULL,
    trade_name VARCHAR(100)                NOT NULL,
    address    VARCHAR(200)                NOT NULL,
    phone      VARCHAR(15),
    active     BOOLEAN                     NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_stores_ruc UNIQUE (ruc)
);

CREATE TABLE currencies (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(3)                  NOT NULL,
    name       VARCHAR(30)                 NOT NULL,
    symbol     VARCHAR(5)                  NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_currencies_code UNIQUE (code)
);

CREATE TABLE measurement_units (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(30)                 NOT NULL,
    abbreviation VARCHAR(10)                 NOT NULL,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_measurement_units_name UNIQUE (name)
);

CREATE TABLE products (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id            BIGINT                      NOT NULL,
    name                VARCHAR(100)                NOT NULL,
    description         VARCHAR(300),
    type                VARCHAR(15)                 NOT NULL,
    supplier            VARCHAR(100),
    brand               VARCHAR(60),
    measurement_unit_id BIGINT,
    image_url           VARCHAR(500),
    cash_price          NUMERIC(12, 2)              NOT NULL,
    credit_price        NUMERIC(12, 2)              NOT NULL,
    active              BOOLEAN                     NOT NULL,
    created_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_products_store FOREIGN KEY (store_id) REFERENCES stores (id),
    CONSTRAINT fk_products_measurement_unit FOREIGN KEY (measurement_unit_id) REFERENCES measurement_units (id),
    CONSTRAINT ck_products_type CHECK (type IN ('PRODUCT', 'SERVICE')),
    CONSTRAINT ck_products_prices CHECK (cash_price > 0 AND credit_price > 0)
);

CREATE INDEX idx_products_store_id ON products (store_id);

